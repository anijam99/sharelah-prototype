// Curated prototype catalogue. Photos are real references; prices and locations
// below are illustrative fixtures, never claims about a current store promotion.
function sample(
  id: string,
  price: number,
  original: number,
  count: number,
  unit: string,
  offer: string,
  store: string,
  category?: string,
): Deal {
  const source = archivedDeals.find((d) => d.id === "photo-" + id)!;
  return {
    ...source,
    demo: true,
    title:
      id === "top-reference" ? "TOP liquid laundry detergent" : source.title,
    priceCents: price,
    originalCents: original,
    bundleCount: count,
    unitPortion: unit,
    portion: `${count} × ${unit}`,
    priceLabel: offer.includes("S$")
      ? offer
      : `${offer} · S$${(price / 100).toFixed(2)}`,
    offerType: offer,
    store,
    category: category || source.category,
    area: "Bugis",
    terms:
      "While stocks last. Check eligible items and the final price at the shelf.",
  };
}
