// Transcribed from the supplied photos. Branches and capture dates are unknown.
function deal(
  id: string,
  file: string,
  title: string,
  store: string,
  category: string,
  priceCents: number,
  priceLabel: string,
  portion: string,
  terms: string,
  bundleCount?: number,
  unitPortion?: string,
): Deal {
  return {
    originalCents: originalPrices[id],
    offerType: bundleCount
      ? `${bundleCount}-item bundle`
      : /2nd/.test(priceLabel)
        ? "Second-item discount"
        : /cashback|rebate/i.test(priceLabel)
          ? "Rewards offer"
          : /%/.test(priceLabel)
            ? "Percentage off"
            : /delivery|voucher/i.test(priceLabel)
              ? "Store offer"
              : "Special price",
    id: "photo-" + id,
    title,
    store,
    category,
    priceCents,
    priceLabel,
    portion,
    terms,
    photo: dealPhoto(id),
    sourceFile: file + (file === "IMG_2069" ? ".png" : ".jpg"),
    area: "Photo collection · branch not shown",
    createdAt: "",
    bundleCount,
    unitPortion,
  };
}
